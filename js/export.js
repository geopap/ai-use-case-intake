// Exports: a Markdown use-case card for decision papers, and conversion of approved
// use cases into initiatives for the AI Portfolio Office (github.com/geopap/ai-portfolio-office).

import { TIERS } from './framework.js';
import { labelOf } from './triage.js';

export function paybackMonths(v = {}) {
  const b = Number(v.benefitK), c = Number(v.costK);
  if (!b || !c) return null;
  return Math.max(1, Math.round((c / b) * 12));
}

export function toMarkdown(uc, r) {
  const status = (id) => ({ done: '[x]', 'in progress': '[~]' }[uc.controlStatus?.[id]] || '[ ]');
  const lines = [
    `# ${uc.id} · ${uc.name}`,
    '',
    `> ${uc.description}`,
    '',
    '| | |', '|---|---|',
    `| Business owner | ${uc.owner} (${uc.function}) |`,
    `| Users | ${labelOf('users', uc.users)} |`,
    `| AI type | ${labelOf('aiType', uc.aiType)} |`,
    `| Sourcing / AI Act role | ${labelOf('sourcing', uc.sourcing)} → **${r.role}** |`,
    `| Decisions about people | ${labelOf('decision', uc.decision)} |`,
    `| Value driver / KPI | ${uc.value.driver} · ${uc.value.kpi} |`,
    `| Annual benefit / cost | €${uc.value.benefitK}k / €${uc.value.costK ?? '–'}k${paybackMonths(uc.value) ? ` · payback ${paybackMonths(uc.value)} months` : ''} |`,
    '',
    `## Risk classification: ${TIERS[r.tier].label}`,
    '',
    ...r.reasons.map((x) => `- ${x.text} *(${x.ref})*`),
    ...r.notes.map((n) => `- Note: ${n}`),
    '',
    `**GDPR:** personal data ${r.personalData ? 'yes' : 'no'} · DPIA ${r.dpia}${r.dpiaCriteria.length ? ` (${r.dpiaCriteria.map((c) => c.label.toLowerCase()).join('; ')})` : ''}`,
    '',
    `## Value & feasibility`,
    '',
    `Value **${r.value}**/100 · Feasibility **${r.feasibility}**/100 · Priority **${r.priority}** · ${r.quadrant}`,
    '',
    `## Review path: ${r.pathInfo.label}`,
    '',
    `${r.pathInfo.who} · target ${r.pathInfo.sla}`,
    '',
  ];
  if (r.controls.length) {
    lines.push(`## Required controls (${r.controls.length})`, '');
    r.controls.forEach((c) => lines.push(`- ${status(c.id)} **${c.id}** ${c.name} — ${[c.aiact, c.iso, c.other].filter((x) => x && x !== '—').join(' · ')}`));
    lines.push('');
  }
  if (uc.triage) {
    lines.push('## Decision', '', `**${uc.triage.outcome}** by ${uc.triage.by} on ${uc.triage.at}`, '', uc.triage.rationale);
    if (uc.triage.conditions) lines.push('', `Conditions: ${uc.triage.conditions}`);
    lines.push('');
  }
  lines.push('---', '*Indicative assessment for illustration, not legal advice. Generated by AI Use-Case Intake.*');
  return lines.join('\n');
}

const OBJECTIVE = {
  'Revenue growth': 'Growth',
  'Customer experience': 'Growth',
  'Cost reduction': 'Cost savings',
  'Risk & compliance': 'Operational excellence',
  'Employee productivity': 'Operational excellence',
};
const clamp = (n) => Math.min(5, Math.max(1, Math.round(n)));

// One approved use case → one initiative in the AI Portfolio Office data model.
export function toInitiative(uc, r, today = new Date().toISOString().slice(0, 10)) {
  const benefitM = (Number(uc.value.benefitK) || 0) / 1000;
  const objective = OBJECTIVE[uc.value.driver] || 'Operational excellence';
  return {
    id: uc.id.replace(/^UC/, 'AI'),
    name: uc.name,
    subtitle: `AI use case · ${TIERS[r.tier].short} risk`,
    objective,
    tier: 'Group pilot',
    markets: ['DE'],
    phase: 'Explore',
    monthsInPhase: 0,
    sponsor: uc.function,
    owner: uc.owner,
    aiSystem: true,
    rag: { timing: 'G', cost: 'G', scope: 'G' },
    budget: Number(uc.value.costK) || 0,
    actuals: 0,
    kpi: null,
    ebitdaYtd: null,
    bc: {
      approved: false,
      netSales: objective === 'Growth' ? Math.round(benefitM * 3 * 10) / 10 : 0,
      ebitda: Math.round(benefitM * 3 * 10) / 10,
      paybackMonths: paybackMonths(uc.value),
    },
    scores: {
      fit: clamp(uc.value.alignment),
      value: clamp(r.value / 20),
      effort: clamp(6 - r.feasibility / 20),
      risk: { high: 5, limited: 3, minimal: 2 }[r.tier] || 3,
    },
    dependsOn: [],
    demand: {},
    lastUpdate: today,
    submitted: true,
    update: `Approved at AI intake: ${TIERS[r.tier].label}, ${r.controls.length} controls required.${uc.triage?.conditions ? ' Conditions: ' + uc.triage.conditions : ''}`.slice(0, 400),
  };
}

export const isApproved = (uc) => ['Approved', 'Approved with conditions'].includes(uc.triage?.outcome);
